"""Build the shipped LOINC subset from the curated code list.

Reads codes.tsv (next to this file) (code, alias_group, method), looks every code and its parts up on the
public FHIR terminology server (tx.fhir.org, LOINC 2.83) and writes
loinc_subset.tsv beside it. Run from backend/:

    uv run python src/ownhealth/normalize/terminology/loinc/build_subset.py

The output is committed; the app never calls the network. Responses are cached in the system
temp folder (ownhealth-loinc-cache).
"""

from __future__ import annotations

import concurrent.futures as cf
import json
import tempfile
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "loinc_subset.tsv"
CACHE = Path(tempfile.gettempdir()) / "ownhealth-loinc-cache"
URL = "https://tx.fhir.org/r4/CodeSystem/$lookup?system=http://loinc.org&code={code}"
COLUMNS = [
    "loinc",
    "alias_group",
    "method",
    "long_name",
    "component",
    "property",
    "time",
    "system",
    "scale",
    "example_ucum",
    "status",
]


def lookup(code: str) -> dict:
    CACHE.mkdir(exist_ok=True)
    f = CACHE / f"{code}.json"
    if f.exists():
        return json.loads(f.read_text())
    req = urllib.request.Request(URL.format(code=code), headers={"Accept": "application/fhir+json"})
    with urllib.request.urlopen(req, timeout=60) as r:
        d = json.load(r)
    f.write_text(json.dumps(d))
    return d


def props(d: dict) -> dict:
    out: dict = {}
    for p in d.get("parameter", []):
        if p["name"] == "display":
            out["display"] = p.get("valueString")
        elif p["name"] == "version":
            out["version"] = p.get("valueString")
        elif p["name"] == "property":
            parts = {q["name"]: q for q in p["part"]}
            v = parts.get("value", {})
            out.setdefault(parts["code"]["valueCode"], v.get("valueString") or v.get("valueCode"))
    return out


def main() -> None:
    rows = []
    for line in (HERE / "codes.tsv").read_text().splitlines():
        if line.startswith("#") or not line.strip():
            continue
        code, group, method = (line.split("\t") + ["", ""])[:3]
        rows.append((code, group, method))
    with cf.ThreadPoolExecutor(6) as ex:
        info = dict(zip([r[0] for r in rows], ex.map(lambda r: props(lookup(r[0])), rows), strict=True))
    part_codes = sorted(
        {
            v
            for p in info.values()
            for k in ("COMPONENT", "PROPERTY", "TIME_ASPCT", "SYSTEM", "SCALE_TYP")
            if (v := p.get(k))
        }
    )
    with cf.ThreadPoolExecutor(6) as ex:
        names = dict(zip(part_codes, ex.map(lambda c: props(lookup(c)).get("display"), part_codes), strict=True))
    versions = {p.get("version") for p in info.values()}
    lines = [
        "# LOINC subset for OwnHealth, generated by normalize/terminology/loinc/build_subset.py from LOINC "
        f"{', '.join(sorted(v for v in versions if v))}. See NOTICE.md (LOINC License).",
        "\t".join(COLUMNS),
    ]
    for code, group, method in rows:
        p = info[code]
        if "display" not in p:
            raise SystemExit(f"{code}: not found in LOINC")
        lines.append(
            "\t".join(
                [
                    code,
                    group,
                    method,
                    p["display"],
                    names.get(p.get("COMPONENT")) or "",
                    names.get(p.get("PROPERTY")) or "",
                    names.get(p.get("TIME_ASPCT")) or "",
                    names.get(p.get("SYSTEM")) or "",
                    names.get(p.get("SCALE_TYP")) or "",
                    p.get("EXAMPLE_UCUM_UNITS") or "",
                    p.get("STATUS") or "",
                ]
            )
        )
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {len(rows)} codes to {OUT}")


if __name__ == "__main__":
    main()
